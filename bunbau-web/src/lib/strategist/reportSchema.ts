import { WaterfallStep } from './allocationPlan';

export type ActionStatus = 'todo' | 'doing' | 'done';
export type RiskLevel = 'Low' | 'Medium' | 'High';

export interface StrategyAction {
  id: string;
  title: string;
  detail: string;
  symbol?: string;
  amountUsd?: number;
  expectedApyImpact: number; // APY percentage points
  risk: RiskLevel;
  status: ActionStatus;
}

export interface StrategyReport {
  headline: string;
  summary: string;
  actions: StrategyAction[];
  risks: string[];
  markdown: string;
}

export const DISCLAIMER =
  'Not financial advice. This report is generated by an AI model from the data you uploaded and is for information only. Verify all figures and consult a licensed professional before acting.';

export const MAX_ACTIONS = 12;

const num = (v: unknown): number | undefined => {
  const n = typeof v === 'number' ? v : typeof v === 'string' ? parseFloat(v) : NaN;
  return Number.isFinite(n) ? n : undefined;
};

/** Pulls the first JSON object out of free text or a ```json fence. */
export function extractJson(raw: string): unknown | null {
  const fence = /```(?:json)?\s*([\s\S]*?)```/i.exec(raw);
  const candidates = [fence?.[1], raw];
  for (const c of candidates) {
    if (!c) continue;
    const start = c.indexOf('{');
    const end = c.lastIndexOf('}');
    if (start >= 0 && end > start) {
      try {
        return JSON.parse(c.slice(start, end + 1));
      } catch {
        /* try next */
      }
    }
  }
  return null;
}

export type ParseResult = { ok: true; report: StrategyReport } | { ok: false; error: string };

export function validateReport(input: unknown): ParseResult {
  if (!input || typeof input !== 'object') return { ok: false, error: 'Not an object' };
  const o = input as Record<string, any>;
  if (typeof o.markdown !== 'string' || !o.markdown.trim()) return { ok: false, error: 'Missing markdown' };
  const rawActions = Array.isArray(o.actions) ? o.actions : [];
  const actions: StrategyAction[] = [];
  for (let i = 0; i < Math.min(rawActions.length, MAX_ACTIONS); i++) {
    const a = rawActions[i] || {};
    if (typeof a.title !== 'string' || !a.title.trim()) return { ok: false, error: `Action ${i + 1} has no title` };
    const impact = num(a.expectedApyImpact);
    if (impact === undefined || impact < -5 || impact > 25) return { ok: false, error: `Action ${i + 1} impact out of range` };
    const amount = num(a.amountUsd);
    if (amount !== undefined && amount < 0) return { ok: false, error: `Action ${i + 1} amount negative` };
    const risk: RiskLevel = a.risk === 'Low' || a.risk === 'High' ? a.risk : 'Medium';
    actions.push({
      id: typeof a.id === 'string' && a.id ? a.id : `a${i + 1}`,
      title: a.title.trim(),
      detail: typeof a.detail === 'string' ? a.detail : '',
      symbol: typeof a.symbol === 'string' ? a.symbol : undefined,
      amountUsd: amount,
      expectedApyImpact: impact,
      risk,
      status: a.status === 'doing' || a.status === 'done' ? a.status : 'todo',
    });
  }
  return {
    ok: true,
    report: {
      headline: typeof o.headline === 'string' ? o.headline : '',
      summary: typeof o.summary === 'string' ? o.summary : '',
      actions,
      risks: Array.isArray(o.risks) ? o.risks.filter((r: unknown) => typeof r === 'string') : [],
      markdown: o.markdown,
    },
  };
}

/** Parse AI output. On failure the caller falls back to a Markdown-only report. */
export function parseReport(raw: string): ParseResult {
  const json = extractJson(raw);
  if (!json) return { ok: false, error: 'No JSON found' };
  return validateReport(json);
}

export function markdownOnlyReport(raw: string): StrategyReport {
  return { headline: '', summary: '', actions: [], risks: [], markdown: raw.trim() };
}

export interface ExportMeta {
  version: number;
  generatedAt: string;
  totalValue: number;
  currentApy: number;
  targetApy: number;
  risk: string;
  modelTag?: string;
}

export function reportToMarkdown(r: StrategyReport, m: ExportMeta, steps?: WaterfallStep[]): string {
  const lines: string[] = [];
  lines.push(`# Yield Strategy Report (v${m.version})`, '');
  lines.push(`- Generated: ${m.generatedAt}`);
  lines.push(`- Portfolio value: $${m.totalValue.toLocaleString('en-US', { maximumFractionDigits: 0 })}`);
  lines.push(`- Current blended APY: ${m.currentApy.toFixed(2)}%  |  Target APY: ${m.targetApy.toFixed(2)}%  |  Risk: ${m.risk}`);
  if (m.modelTag) lines.push(`- Model: ${m.modelTag}`);
  lines.push('');
  if (r.headline) lines.push(`## ${r.headline}`, '');
  if (r.summary) lines.push(r.summary, '');
  lines.push(r.markdown.trim(), '');
  if (r.actions.length) {
    lines.push('## Action plan', '');
    r.actions.forEach((a, i) => {
      const amt = a.amountUsd !== undefined ? ` ($${a.amountUsd.toLocaleString('en-US')})` : '';
      lines.push(
        `${i + 1}. [${a.status === 'done' ? 'x' : ' '}] **${a.title}**${a.symbol ? ` ${a.symbol}` : ''}${amt}, APY ${a.expectedApyImpact >= 0 ? '+' : ''}${a.expectedApyImpact.toFixed(2)} pts, risk ${a.risk}${a.detail ? `. ${a.detail}` : ''}`
      );
    });
    lines.push('');
  }
  if (steps && steps.length) {
    lines.push('## Path to target APY', '');
    steps.forEach((s) => lines.push(`- ${s.label}: ${s.delta === null ? '' : `${s.delta >= 0 ? '+' : ''}${s.delta.toFixed(2)} → `}${s.running.toFixed(2)}%`));
    lines.push('');
  }
  if (r.risks.length) {
    lines.push('## Risks', '');
    r.risks.forEach((x) => lines.push(`- ${x}`));
    lines.push('');
  }
  lines.push('---', `_${DISCLAIMER}_`, '');
  return lines.join('\n');
}
